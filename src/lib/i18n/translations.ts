export type TranslationKey = (typeof translations)[Locale];

export function getTranslation(locale: Locale) {
  return translations[locale] || translations.ar;
}

export function t(
  locale: Locale,
  section: keyof TranslationKey,
  key: string
): string {
  const sectionData = translations[locale][section] as Record<string, string>;
  return sectionData[key] || key;
}

export function getLocalizedField<T extends Record<string, unknown>>(
  item: T,
  field: string,
  locale: Locale
): string {
  const localizedKey = `${field}${locale === "ar" ? "Ar" : "En"}`;
  const value = item[localizedKey] ?? item[field];
  return (value as string) || "";
}
